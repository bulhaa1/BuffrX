# Extracts the pinned libobs public headers from the OBS sources archive and resolves the exact
# WebView2 include/library paths from the toolchain cache. Writes work/paths.json, which the build
# script passes to CMake. Never edits runtime/ contents that prepare-runtime.ps1 produced.

$ErrorActionPreference = 'Stop'
$root = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$work = Join-Path $root 'work'
$tools = Get-Content -LiteralPath (Join-Path $work 'toolchain.json') -Raw | ConvertFrom-Json
# Windows' own tar (bsdtar) by full path: it understands --include. Started from Git Bash, a bare "tar.exe" is Git's GNU tar,
# which does not.
$bsdtar = Join-Path $env:SystemRoot 'System32\tar.exe'

# The version prepare-runtime.ps1 staged (runtime\pin.json): the headers must be the ones of the obs.dll the engine links.
$pinFile = Join-Path $root 'runtime\pin.json'
if (-not (Test-Path $pinFile)) { throw "runtime\pin.json missing - run tools/prepare-runtime.ps1" }
$obsVersion = (Get-Content -LiteralPath $pinFile -Raw | ConvertFrom-Json).version
$sources = Join-Path $work "obs\OBS-Studio-$obsVersion-Sources.tar.gz"
if (-not (Test-Path $sources)) { throw "sources archive missing: $sources - run tools/prepare-runtime.ps1" }

$extract = Join-Path $work 'obs\sources'
$include = Join-Path $root 'runtime\include\libobs'
$includeVersion = Join-Path $include '.obs-version'
New-Item -ItemType Directory -Force $extract | Out-Null

$current = (Test-Path (Join-Path $include 'obs.h')) -and (Test-Path $includeVersion) -and
  ((Get-Content -LiteralPath $includeVersion -Raw).Trim() -eq $obsVersion)
if (-not $current) {
  Write-Host "extracting libobs $obsVersion headers from the pinned sources"
  # bsdtar (shipped with Windows) understands --include; the archive root is obs-studio-<version>/
  & $bsdtar -xf $sources -C $extract --include '*/libobs/*'
  if ($LASTEXITCODE -ne 0) { throw 'header extraction failed' }

  # Only this version's tree: an earlier pin's extraction may sit beside it.
  $libobs = @(Get-ChildItem -LiteralPath $extract | Where-Object { $_.PSIsContainer -and ($_.Name -eq "obs-studio-$obsVersion-sources" -or $_.Name -eq "obs-studio-$obsVersion") } | ForEach-Object {
    Join-Path $_.FullName 'libobs'
  } | Where-Object { Test-Path $_ })
  if ($libobs.Count -eq 0) { throw "no libobs directory for $obsVersion inside the extracted sources" }

  if (Test-Path $include) { Remove-Item -LiteralPath $include -Recurse -Force }
  New-Item -ItemType Directory -Force (Split-Path -Parent $include) | Out-Null
  Copy-Item -LiteralPath $libobs[0] -Destination $include -Recurse -Force
  Get-ChildItem -LiteralPath $include -Recurse -File -Filter '*.in' | ForEach-Object {
    # "config.h.in"-style templates are not headers. obsconfig.h is written below by hand because the
    # OBS build generates it from CMake variables we resolve at runtime instead.
    if ($_.Name -eq 'obsconfig.h.in') { return }
    $generated = $_.FullName -replace '\.in$', ''
    $text = Get-Content -LiteralPath $_.FullName -Raw
    $text = $text -replace '@OBS_DATA_PATH@', ''
    $text = $text -replace '@OBS_PLUGIN_PATH@', ''
    $text = $text -replace '@OBS_PLUGIN_DESTINATION@', 'obs-plugins/64bit'
    $text = $text -replace '@OBS_RELATIVE_PREFIX@', '.'
    $text = $text -replace '@CMAKE_INSTALL_PREFIX@', '.'
    Set-Content -LiteralPath $generated -Value $text -NoNewline
  }
  Set-Content -LiteralPath $includeVersion -Value $obsVersion -NoNewline
}

$config = Join-Path $include 'obsconfig.h'
if (-not (Test-Path $config)) {
  # obsconfig.h is generated by the OBS build. These are the defines the public headers need; paths
  # are resolved at runtime by the engine, never baked in here.
  @(
    '#pragma once',
    '#define OBS_DATA_PATH ""',
    '#define OBS_PLUGIN_PATH "obs-plugins/64bit"',
    '#define OBS_PLUGIN_DESTINATION "obs-plugins/64bit"',
    '#define OBS_RELATIVE_PREFIX "."',
    '#define OBS_INSTALL_PREFIX "."'
  ) | Set-Content -LiteralPath $config -Encoding ascii
}

# FFmpeg headers for the editor's remux and the library's thumbnails and durations. The pinned OBS
# release ships FFmpeg as DLLs (avformat-62, avcodec-62, avutil-60, swscale-9, swresample-6) and its
# version string says n8.1.2, so the headers are pinned to that release rather than to a rolling build.
$ffmpegVersion = '8.1.2'
$ffmpegInclude = Join-Path $root 'runtime\include\ffmpeg'
if (-not (Test-Path (Join-Path $ffmpegInclude 'libavfilter\avfilter.h'))) {
  $archive = Join-Path $work "ffmpeg\ffmpeg-$ffmpegVersion.tar.gz"
  New-Item -ItemType Directory -Force (Split-Path -Parent $archive) | Out-Null
  if (-not (Test-Path $archive)) {
    $url = "https://ffmpeg.org/releases/ffmpeg-$ffmpegVersion.tar.gz"
    Write-Host "downloading $url"
    & curl.exe -fL --retry 3 --silent --show-error $url -o $archive
    if ($LASTEXITCODE -ne 0) { throw "FFmpeg $ffmpegVersion download failed" }
  }
  $expected = '32faba5ef67340d54724941eae1425580791195312a4fd13bf6f820a2818bf22'
  $hash = (Get-FileHash -LiteralPath $archive -Algorithm SHA256).Hash.ToLowerInvariant()
  if ($hash -ne $expected) { throw "ffmpeg-$ffmpegVersion.tar.gz hash mismatch: $hash" }
  $extract = Join-Path $work 'ffmpeg\extract'
  if (Test-Path $extract) { Remove-Item -LiteralPath $extract -Recurse -Force }
  New-Item -ItemType Directory -Force $extract | Out-Null
  & $bsdtar -xf $archive -C $extract --include '*/libavformat/*' --include '*/libavcodec/*' --include '*/libavutil/*' --include '*/libswscale/*' --include '*/libswresample/*' --include '*/libavfilter/*'
  if ($LASTEXITCODE -ne 0) { throw 'FFmpeg header extraction failed' }
  $rootDir = Get-ChildItem -LiteralPath $extract | Where-Object { $_.PSIsContainer } | Select-Object -First 1
  if (-not $rootDir) { throw 'no directory inside the FFmpeg archive' }
  if (Test-Path $ffmpegInclude) { Remove-Item -LiteralPath $ffmpegInclude -Recurse -Force }
  New-Item -ItemType Directory -Force $ffmpegInclude | Out-Null
  foreach ($library in @('libavformat', 'libavcodec', 'libavutil', 'libswscale', 'libswresample', 'libavfilter')) {
    Copy-Item -LiteralPath (Join-Path $rootDir.FullName $library) -Destination $ffmpegInclude -Recurse -Force
  }
  # Two headers come from FFmpeg's own build system. Writing them by hand is the same choice the libobs
  # headers above make for obsconfig.h: the values are properties of the shipped DLLs, not of a build.
  @(
    '#ifndef AVUTIL_AVCONFIG_H',
    '#define AVUTIL_AVCONFIG_H',
    '#define AV_HAVE_BIGENDIAN 0',
    '#define AV_HAVE_FAST_UNALIGNED 1',
    '#endif'
  ) | Set-Content -LiteralPath (Join-Path $ffmpegInclude 'libavutil\avconfig.h') -Encoding ascii
  @(
    '#ifndef AVUTIL_FFVERSION_H',
    '#define AVUTIL_FFVERSION_H',
    "#define FFMPEG_VERSION `"$ffmpegVersion`"",
    '#endif'
  ) | Set-Content -LiteralPath (Join-Path $ffmpegInclude 'libavutil\ffversion.h') -Encoding ascii
  Write-Host "FFmpeg $ffmpegVersion headers staged in runtime/include/ffmpeg"
}

$wvRoot = Join-Path $work 'toolchain\webview2'
$wv = Get-ChildItem -LiteralPath $wvRoot -Recurse -File -Filter 'WebView2.h' | Select-Object -First 1
if (-not $wv) { throw 'WebView2.h not found in the toolchain cache' }
$wvInclude = Split-Path -Parent $wv.FullName
# The loader sits beside the headers in the nuget layout (build/native/x64), not under the include
# directory; the shell links its import library and ships the DLL.
$loader = Get-ChildItem -LiteralPath $wvRoot -Recurse -File -Filter 'WebView2Loader.dll' |
  Where-Object { $_.FullName -match '\\x64\\' } | Select-Object -First 1
$loaderDir = if ($loader) { $loader.DirectoryName } else { '' }

$paths = [ordered]@{
  obs_include       = (Join-Path $root 'runtime\include')
  obs_lib           = (Join-Path $root 'runtime\lib')
  runtime_root      = (Join-Path $root 'runtime')
  webview2_include  = $wvInclude
  webview2_loader   = if ($loader) { $loader.FullName } else { '' }
  llvm_bin          = $tools.llvm_root + '\bin'
  clang             = $tools.clang
  clangxx           = $tools.clangxx
  cmake             = $tools.cmake
  ninja             = $tools.ninja
}
$out = Join-Path $work 'paths.json'
$paths | ConvertTo-Json | Set-Content -LiteralPath $out
Write-Host "PATHS_READY $out"
foreach ($key in $paths.Keys) { Write-Host ("  {0,-18} {1}" -f $key, $paths[$key]) }
